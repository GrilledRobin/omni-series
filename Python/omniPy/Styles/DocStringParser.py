@dataclass
class CellPoint:
    text : str
    point_num : Optional[str] = None
    point_val : Optional[str] = None
    type_ : str = 'point'
    indent_out : int = 0

@dataclass
class CellDict:
    text : str
    dict_key : Optional[str] = None
    dict_val : Optional[str] = None
    type_ : str = 'dict'
    indent_out : int = 0

@dataclass
class CellField:
    text : str
    field_name : Optional[str] = None
    field_default : bool = False
    field_val : Optional[str] = None
    type_ : str = 'field'
    indent_out : int = 0

@dataclass
class TableCell:
    # {栈}中的元素，包含{名称}与{值}，以及宽度（用于<td colspan>）
    name : str
    value : str
    width : int = 1
    # {表格要点}（可选）
    points : list[CellPoint] = field(default_factory = list)
    dicts : list[CellDict] = field(default_factory = list)
    fields : list[CellField] = field(default_factory = list)
    # {表格文本}（可选）
    text : Optional[str] = None

@dataclass
class Item:
    # 行的原始值（去掉 # ... # 标识及首尾空格后的行文本，保留行内前导空格）
    raw : str
    # 去掉前后空格的净文本
    text : str
    # {缩进}等级（0 起）
    indent : int
    # Indent_out for output items, esp. for point / dict / field
    #[ASSUMPTION]
    #[1] 0 for all headers as it is designed for Markdown
    #[2] Plus 1 for each additional <indent>
    indent_out : int = 0
    # 是否能延续缩进，当某项是 {标题} 且缩进大于 0 时，其子项的缩进无法被 Markdown正确识别
    indent_cont : bool = True
    # 父子关系
    parent_id : Optional[str] = None
    id_ : int = -1
    # 类型： header_ordered / header_paragraph / point / dict / field / table / log_table / body / free / cont / deleted
    type_ : str = 'unknown'

    # 标题相关
    ordered_title : Optional[str] = None
    paragraph_title : Optional[str] = None

    # 要点相关
    point_num : Optional[str] = None
    point_val : Optional[str] = None

    # 字典相关
    dict_key : Optional[str] = None
    dict_val : Optional[str] = None

    # 字段相关
    field_name : Optional[str] = None
    field_default : bool = False
    field_val : Optional[str] = None

    # 表格相关
    table_cells : list[TableCell] = field(default_factory = list)

    # 行内前导空格数量（用于 {要点}/{字典}/{字段} 的缩进比较规则）
    leading_spaces_count : int = 0

